-- Locked-layout website CMS. Marketplace operational data remains separate.

create table if not exists public.website_pages (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  path text not null unique,
  title text not null,
  draft_content jsonb not null default '{}'::jsonb,
  published_content jsonb not null default '{}'::jsonb,
  draft_updated_at timestamptz not null default now(),
  published_at timestamptz,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint website_pages_slug_shape
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint website_pages_path_shape
    check (path = '/' or path ~ '^/[a-z0-9]+(?:[-/][a-z0-9]+)*$'),
  constraint website_pages_draft_object
    check (jsonb_typeof(draft_content) = 'object'),
  constraint website_pages_published_object
    check (jsonb_typeof(published_content) = 'object')
);

create table if not exists public.website_page_versions (
  id bigint generated by default as identity primary key,
  page_id bigint not null references public.website_pages(id) on delete cascade,
  version_number integer not null,
  content jsonb not null,
  published_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint website_page_versions_content_object
    check (jsonb_typeof(content) = 'object'),
  constraint website_page_versions_number_positive
    check (version_number > 0),
  unique (page_id, version_number)
);

create index if not exists website_page_versions_page_created_idx
  on public.website_page_versions (page_id, created_at desc);

alter table public.website_pages enable row level security;
alter table public.website_pages force row level security;
alter table public.website_page_versions enable row level security;
alter table public.website_page_versions force row level security;

create policy website_pages_no_client_access
on public.website_pages
for all
to anon, authenticated
using (false)
with check (false);

create policy website_page_versions_no_client_access
on public.website_page_versions
for all
to anon, authenticated
using (false)
with check (false);

revoke all on table public.website_pages
from public, anon, authenticated;
revoke all on table public.website_page_versions
from public, anon, authenticated;
grant all on table public.website_pages to service_role;
grant all on table public.website_page_versions to service_role;
grant usage, select on sequence public.website_pages_id_seq to service_role;
grant usage, select on sequence public.website_page_versions_id_seq to service_role;

