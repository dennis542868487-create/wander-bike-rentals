create or replace function public.publish_website_page(
  p_slug text,
  p_actor_id uuid
)
returns public.website_pages
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_page public.website_pages;
  v_next_version integer;
begin
  update public.website_pages
  set published_content = draft_content,
      published_at = now(),
      updated_at = now(),
      updated_by = p_actor_id
  where slug = p_slug
  returning * into v_page;

  if v_page.id is null then
    raise exception 'Website page not found';
  end if;

  select coalesce(max(version_number), 0) + 1
  into v_next_version
  from public.website_page_versions
  where page_id = v_page.id;

  insert into public.website_page_versions (
    page_id,
    version_number,
    content,
    published_by
  )
  values (
    v_page.id,
    v_next_version,
    v_page.published_content,
    p_actor_id
  );

  return v_page;
end;
$$;

revoke all on function public.publish_website_page(text, uuid)
from public, anon, authenticated;
grant execute on function public.publish_website_page(text, uuid)
to service_role;

